-- 租户表: 系统多租户隔离的核心表，每个租户拥有独立的数据空间
CREATE TABLE IF NOT EXISTS sys_tenant (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       VARCHAR(64)  NOT NULL UNIQUE,
    name            VARCHAR(128) NOT NULL,
    status          VARCHAR(32)  NOT NULL DEFAULT 'ACTIVE',
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 系统配置表: 存储租户级系统参数配置
CREATE TABLE IF NOT EXISTS sys_config (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_id       VARCHAR(64)  NOT NULL UNIQUE,
    tenant_id       VARCHAR(64)  NOT NULL,
    config_key      VARCHAR(128) NOT NULL,
    config_value    VARCHAR(1024) NOT NULL,
    description     VARCHAR(255),
    enabled         BOOLEAN      NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (tenant_id, config_key)
);

-- PMS推荐表: 存储AI智能推荐系统(PMS)生成的业务建议，ERP作为审批和执行主控
CREATE TABLE IF NOT EXISTS sys_pms_recommendation (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    erp_reference_id    VARCHAR(64)  NOT NULL UNIQUE,
    tenant_id           VARCHAR(64)  NOT NULL,
    recommendation_id   VARCHAR(64)  NOT NULL,
    domain              VARCHAR(64)  NOT NULL,
    recommendation_type VARCHAR(64)  NOT NULL,
    object_type         VARCHAR(64),
    target_object_type  VARCHAR(64),
    target_object_id    VARCHAR(64),
    content             TEXT         NOT NULL,
    score               DECIMAL(8, 4),
    confidence          DECIMAL(8, 4),
    evidence_chain_id   VARCHAR(64),
    data_sources        VARCHAR(1024),
    risk_flags          VARCHAR(1024),
    explainability      TEXT,
    requested_action    VARCHAR(64)  NOT NULL,
    status              VARCHAR(32)  NOT NULL DEFAULT 'DRAFT',
    approval_policy     VARCHAR(64),
    rejection_reason    VARCHAR(512),
    execution_result    TEXT,
    measured_result     TEXT,
    trace_id            VARCHAR(128),
    idempotency_key     VARCHAR(128) NOT NULL,
    actor_id            VARCHAR(64),
    actor_type          VARCHAR(32),
    agent_id            VARCHAR(64),
    scope               TEXT,
    purpose             VARCHAR(128),
    source_system       VARCHAR(32),
    audit_id            VARCHAR(64),
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (tenant_id, idempotency_key)
);

CREATE INDEX IF NOT EXISTS idx_pms_rec_tenant ON sys_pms_recommendation(tenant_id);
CREATE INDEX IF NOT EXISTS idx_pms_rec_domain ON sys_pms_recommendation(tenant_id, domain);
CREATE INDEX IF NOT EXISTS idx_pms_rec_status ON sys_pms_recommendation(tenant_id, status);
CREATE INDEX IF NOT EXISTS idx_pms_rec_idempotency ON sys_pms_recommendation(tenant_id, idempotency_key);

