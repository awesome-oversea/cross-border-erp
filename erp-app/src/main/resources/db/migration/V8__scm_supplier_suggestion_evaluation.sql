CREATE TABLE IF NOT EXISTS scm_supplier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id VARCHAR(64) NOT NULL UNIQUE,
    tenant_id VARCHAR(64) NOT NULL,
    name VARCHAR(256) NOT NULL,
    contact_name VARCHAR(128),
    country_code VARCHAR(8),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_scm_supplier_tenant ON scm_supplier(tenant_id);

CREATE TABLE IF NOT EXISTS scm_purchase_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id VARCHAR(64) NOT NULL UNIQUE,
    tenant_id VARCHAR(64) NOT NULL,
    supplier_id VARCHAR(64) NOT NULL,
    currency VARCHAR(8) NOT NULL DEFAULT 'CNY',
    total_amount DECIMAL(18, 2),
    status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_scm_po_tenant ON scm_purchase_order(tenant_id);

CREATE TABLE IF NOT EXISTS scm_purchase_order_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id VARCHAR(64) NOT NULL,
    line_id VARCHAR(64) NOT NULL,
    seller_sku VARCHAR(128) NOT NULL,
    quantity INT NOT NULL DEFAULT 0,
    received_quantity INT NOT NULL DEFAULT 0,
    unit_cost DECIMAL(18, 4),
    UNIQUE(po_id, line_id)
);

CREATE INDEX idx_scm_pol_po ON scm_purchase_order_line(po_id);

CREATE TABLE IF NOT EXISTS scm_replenishment_suggestion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suggestion_id VARCHAR(64) NOT NULL UNIQUE,
    tenant_id VARCHAR(64) NOT NULL,
    seller_sku VARCHAR(128) NOT NULL,
    warehouse_id VARCHAR(64),
    current_stock INT NOT NULL DEFAULT 0,
    avg_daily_sales INT NOT NULL DEFAULT 0,
    lead_time_days INT NOT NULL DEFAULT 0,
    safety_stock INT NOT NULL DEFAULT 0,
    suggested_quantity INT NOT NULL DEFAULT 0,
    priority VARCHAR(16) NOT NULL DEFAULT 'MEDIUM',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_scm_suggestion_tenant ON scm_replenishment_suggestion(tenant_id);
CREATE INDEX idx_scm_suggestion_status ON scm_replenishment_suggestion(tenant_id, status);

CREATE TABLE IF NOT EXISTS scm_supplier_evaluation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id VARCHAR(64) NOT NULL UNIQUE,
    tenant_id VARCHAR(64) NOT NULL,
    supplier_id VARCHAR(64) NOT NULL,
    quality_score DECIMAL(5, 2),
    delivery_score DECIMAL(5, 2),
    price_score DECIMAL(5, 2),
    service_score DECIMAL(5, 2),
    overall_score DECIMAL(5, 2),
    comment TEXT,
    evaluated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_scm_eval_supplier ON scm_supplier_evaluation(tenant_id, supplier_id);
