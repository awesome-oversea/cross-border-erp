CREATE TABLE IF NOT EXISTS wms_warehouse_location (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id VARCHAR(64) NOT NULL UNIQUE,
    tenant_id VARCHAR(64) NOT NULL,
    warehouse_id VARCHAR(64) NOT NULL,
    zone_code VARCHAR(64),
    aisle VARCHAR(64),
    rack VARCHAR(64),
    shelf VARCHAR(64),
    bin VARCHAR(64),
    barcode VARCHAR(128),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS wms_stock_check (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_id VARCHAR(64) NOT NULL UNIQUE,
    tenant_id VARCHAR(64) NOT NULL,
    warehouse_id VARCHAR(64) NOT NULL,
    check_type VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    scheduled_at TIMESTAMP,
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS wms_stock_check_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_id VARCHAR(64) NOT NULL,
    tenant_id VARCHAR(64) NOT NULL,
    seller_sku VARCHAR(128) NOT NULL,
    location_id VARCHAR(64),
    system_qty INT NOT NULL DEFAULT 0,
    actual_qty INT,
    diff_qty INT,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS wms_inventory_prediction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_id VARCHAR(64) NOT NULL UNIQUE,
    tenant_id VARCHAR(64) NOT NULL,
    warehouse_id VARCHAR(64) NOT NULL,
    seller_sku VARCHAR(128) NOT NULL,
    predicted_demand INT,
    predicted_days_of_supply DECIMAL(10, 2),
    recommended_restock_qty INT,
    confidence DECIMAL(5, 4),
    model_version VARCHAR(64),
    prediction_date DATE NOT NULL,
    horizon_days INT NOT NULL DEFAULT 30,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_wms_location_tenant_wh ON wms_warehouse_location(tenant_id, warehouse_id);
CREATE INDEX idx_wms_stock_check_tenant_wh ON wms_stock_check(tenant_id, warehouse_id);
CREATE INDEX idx_wms_prediction_tenant_wh ON wms_inventory_prediction(tenant_id, warehouse_id);
CREATE INDEX idx_wms_prediction_sku ON wms_inventory_prediction(tenant_id, seller_sku);
